-- ERDCloud Import용 (DB: MySQL / MariaDB)

CREATE TABLE AI_INSPECTION (
    INSPECTION_ID   BIGINT(8)       NOT NULL AUTO_INCREMENT COMMENT '원천 데이터ID',
    IMAGE_PATH      NVARCHAR(500)   NULL COMMENT '이미지 경로',
    PICTURE_TIME    DATETIME        NULL COMMENT '촬영 일시',
    LINE_NUMBER     NVARCHAR(64)    NULL COMMENT '라인 번호',
    DEFECT_YN       TINYINT(1)      NULL COMMENT '불량 여부',
    REMARK          NVARCHAR(200)   NULL COMMENT '비고',
    PRIMARY KEY (INSPECTION_ID)
) COMMENT = '품질검사 원천 데이터';

CREATE TABLE AI_INSPECTION_PP (
    INSPECTION_PP_ID BIGINT(8)      NOT NULL AUTO_INCREMENT COMMENT '전처리 이미지 ID',
    INSPECTION_ID    BIGINT(8)      NOT NULL COMMENT '원천 데이터ID',
    IMAGE_PP_PATH    NVARCHAR(500)  NULL COMMENT '전처리 이미지 경로',
    PP_TIME          DATETIME       NULL COMMENT '전처리 일시',
    DEFECT_YN        TINYINT(1)     NULL COMMENT '불량 여부',
    DEFECT_TYPE      NVARCHAR(8)    NULL COMMENT '불량 유형',
    YOLO_TXT         NVARCHAR(500)  NULL COMMENT 'yolo_txt',
    REMARK           NVARCHAR(200)  NULL COMMENT '비고',
    PRIMARY KEY (INSPECTION_PP_ID),
    CONSTRAINT FK_AI_INSPECTION_PP_INSPECTION FOREIGN KEY (INSPECTION_ID)
        REFERENCES AI_INSPECTION (INSPECTION_ID)
) COMMENT = '품질검사 전처리 데이터';

CREATE TABLE AI_INSPECTION_MODEL_TRAIN (
    TRAIN_MODEL_ID  BIGINT(8)       NOT NULL AUTO_INCREMENT COMMENT '학습 모델 ID',
    MODEL_NAME      NVARCHAR(120)   NULL COMMENT '모델명',
    MODEL_PATH      NVARCHAR(200)   NULL COMMENT '모델경로',
    LATEST_DATA_DT  DATETIME        NULL COMMENT '최신 데이터 시각',
    ALGORITHM       NVARCHAR(80)    NULL COMMENT '알고리즘',
    TRAIN_TIME      INT             NULL COMMENT '학습시간',
    TRAIN_DATETIME  DATETIME        NULL COMMENT '학습일시',
    ACCURACY        DOUBLE          NULL COMMENT '산출 정확도',
    LOSS            DOUBLE          NULL COMMENT '손실 값',
    VAL_LOSS        DOUBLE          NULL COMMENT '검증 손실값',
    MAP_SCORE       DOUBLE          NULL COMMENT 'mAP50 값',
    REMARK          NVARCHAR(200)   NULL COMMENT '비고',
    PRIMARY KEY (TRAIN_MODEL_ID)
) COMMENT = '품질검사 AI 모델 학습 정보';

CREATE TABLE AI_INSPECTION_RES (
    PRED_ID           BIGINT(8)     NOT NULL AUTO_INCREMENT COMMENT '판별 결과ID',
    TRAIN_MODEL_ID    BIGINT(8)     NOT NULL COMMENT '학습 모델 ID',
    INSPECTION_PP_ID  BIGINT(8)     NOT NULL COMMENT '전처리 이미지 ID',
    DEFECT_YN         TINYINT(1)    NULL COMMENT '불량 여부',
    DEFECT_TYPE       NVARCHAR(8)   NULL COMMENT '불량 유형',
    PRED_DATETIME     DATETIME      NULL COMMENT '판별 일시',
    CONFIDENCE        DOUBLE        NULL COMMENT '신뢰도',
    DETECT_TXT        NVARCHAR(500) NULL COMMENT '탐지 결과',
    DETECT_CNT        INT           NULL COMMENT '탐지 개수',
    RESULT_IMAGE_PATH NVARCHAR(500) NULL COMMENT '결과 이미지 경로',
    CONF_THRESHOLD    DOUBLE        NULL COMMENT '신뢰도 임계값',
    INFERENCE_TIME    INT           NULL COMMENT '추론 시간',
    REMARK            NVARCHAR(200) NULL COMMENT '비고',
    PRIMARY KEY (PRED_ID),
    CONSTRAINT FK_AI_INSPECTION_RES_TRAIN FOREIGN KEY (TRAIN_MODEL_ID)
        REFERENCES AI_INSPECTION_MODEL_TRAIN (TRAIN_MODEL_ID),
    CONSTRAINT FK_AI_INSPECTION_RES_PP FOREIGN KEY (INSPECTION_PP_ID)
        REFERENCES AI_INSPECTION_PP (INSPECTION_PP_ID)
) COMMENT = '품질검사 판별 결과';

CREATE TABLE DASHBOARD_MONTHLY_DEFECT_RATE (
    STAT_ID         BIGINT(8)       NOT NULL AUTO_INCREMENT COMMENT '집계ID',
    STAT_MONTH      INT             NULL COMMENT '집계월',
    LINE_NUMBER     NVARCHAR(64)    NULL COMMENT '라인 번호',
    TOTAL_CNT       INT             NULL COMMENT '전체 검사 수',
    DEFECT_CNT      INT             NULL COMMENT '불량 수',
    DEFECT_RATE     NUMERIC(5,2)    NULL COMMENT '불량율',
    REMARK          NVARCHAR(200)   NULL COMMENT '비고',
    PRIMARY KEY (STAT_ID)
) COMMENT = '월별 불량율';

CREATE TABLE DASHBOARD_PROD_MONTHLY (
    STAT_ID         BIGINT(8)       NOT NULL AUTO_INCREMENT COMMENT '집계ID',
    STAT_MONTH      INT             NULL COMMENT '집계월',
    LINE_NUMBER     NVARCHAR(64)    NULL COMMENT '라인 번호',
    TOTAL_QTY       INT             NULL COMMENT '월 총 생산량',
    OPERATING_HOURS NUMERIC(8,2)    NULL COMMENT '월 가동 시간',
    AVG_HOURLY_QTY  NUMERIC(10,2)   NULL COMMENT '시간당 평균 생산량',
    REMARK          NVARCHAR(200)   NULL COMMENT '비고',
    PRIMARY KEY (STAT_ID)
) COMMENT = '월 평균 시간당 생산량';
